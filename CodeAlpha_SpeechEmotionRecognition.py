# 1. Feature Extraction Function (Extracting MFCCs, Chroma, and Mel features warning-free)
def extract_feature(file_name: str, mfcc: bool = True, chroma: bool = True, mel: bool = True) -> np.ndarray | None:
    """
    Extracts MFCC, Chroma, and Mel features from an audio file using modern, warning-free syntax.
    """
    try:
        # Load audio using modern keyword arguments
        X, sample_rate = librosa.load(file_name, sr=None)
        result = np.array([], dtype=np.float32)

        if mfcc:
            mfccs = np.mean(librosa.feature.mfcc(y=X, sr=sample_rate, n_mfcc=40).T, axis=0)
            result = np.hstack((result, mfccs))
        if chroma:
            chroma_feat = np.mean(librosa.feature.chroma_stft(y=X, sr=sample_rate).T, axis=0)
            result = np.hstack((result, chroma_feat))
        if mel:
            mel_feat = np.mean(librosa.feature.melspectrogram(y=X, sr=sample_rate).T, axis=0)
            result = np.hstack((result, mel_feat))

        return result
    except Exception as e:
        print(f"Error processing {file_name}: {e}")
        return None

